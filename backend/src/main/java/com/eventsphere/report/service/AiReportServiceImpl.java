package com.eventsphere.report.service;

import com.eventsphere.ai.provider.LlmProvider;
import com.eventsphere.attendance.repository.AttendanceRepository;
import com.eventsphere.auth.entity.User;
import com.eventsphere.auth.repository.UserRepository;
import com.eventsphere.common.exception.ResourceNotFoundException;
import com.eventsphere.common.tenant.TenantContext;
import com.eventsphere.event.entity.Event;
import com.eventsphere.event.repository.EventRepository;
import com.eventsphere.registration.entity.RegistrationStatus;
import com.eventsphere.registration.repository.RegistrationRepository;
import com.eventsphere.report.dto.ReportGenerateRequest;
import com.eventsphere.report.dto.ReportResponse;
import com.eventsphere.report.entity.AiReport;
import com.eventsphere.report.repository.AiReportRepository;
import com.eventsphere.volunteer.repository.VolunteerRepository;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Pageable;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.nio.charset.StandardCharsets;

@Service
@RequiredArgsConstructor
@Slf4j
public class AiReportServiceImpl implements AiReportService {

    private final AiReportRepository reportRepository;
    private final EventRepository eventRepository;
    private final RegistrationRepository registrationRepository;
    private final AttendanceRepository attendanceRepository;
    private final VolunteerRepository volunteerRepository;
    private final UserRepository userRepository;
    private final LlmProvider llmProvider;

    @Override
    @Transactional
    public ReportResponse generateReport(String currentUserId, ReportGenerateRequest request) {
        String tenantId = TenantContext.getTenantId();
        log.info("Generating AI Report '{}' for event '{}'", request.getReportType(), request.getEventId());

        Event event = eventRepository.findByIdAndTenantId(request.getEventId(), tenantId)
                .orElseThrow(() -> new ResourceNotFoundException("Event not found"));

        User user = userRepository.findById(currentUserId).orElse(null);

        long regCount = registrationRepository.countByTenantIdAndEventIdAndStatusAndDeletedFalse(tenantId, request.getEventId(), RegistrationStatus.CONFIRMED);
        long attCount = attendanceRepository.countByTenantIdAndEventIdAndStatusAndDeletedFalse(tenantId, request.getEventId(), "CHECKED_IN");
        long volCount = volunteerRepository.findByTenantIdAndEventIdAndDeletedFalse(tenantId, request.getEventId(), PageRequest.of(0, 100))
                .getContent().stream().filter(v -> "APPROVED".equalsIgnoreCase(v.getStatus())).count();

        String reportType = request.getReportType().toUpperCase();
        String title = request.getCustomTitle() != null && !request.getCustomTitle().isBlank() ?
                request.getCustomTitle() : event.getTitle() + " - " + reportType + " Report";

        String systemPrompt = "You are EventSphere AI Executive Report Writer. Produce a professional GitHub Markdown formatted report with sections, key metrics, and operational recommendations.";
        String userPrompt = String.format("Report Type: %s, Event: %s, Max Capacity: %d, Confirmed Registrations: %d, Actual Check-ins: %d, Active Volunteers: %d",
                reportType, event.getTitle(), event.getMaxCapacity(), regCount, attCount, volCount);

        LlmProvider.LlmResponse llmResp = llmProvider.generateCompletion(systemPrompt, userPrompt);

        String markdownContent = "# " + title + "\n\n" +
                "**Generated By:** EventSphere AI System\n" +
                "**Tenant ID:** " + tenantId + "\n\n" +
                "## Executive Summary\n" +
                llmResp.text() + "\n\n" +
                "## Operational Breakdown\n" +
                "- **Total Registrations:** " + regCount + "\n" +
                "- **Actual Attendance:** " + attCount + "\n" +
                "- **Active Volunteers:** " + volCount + "\n" +
                "- **Turnout Rate:** " + (regCount > 0 ? (double) attCount / regCount * 100.0 : 0.0) + "%\n";

        AiReport report = AiReport.builder()
                .tenantId(tenantId)
                .event(event)
                .reportType(reportType)
                .title(title)
                .markdownContent(markdownContent)
                .status("COMPLETED")
                .generatedBy(user)
                .build();

        AiReport saved = reportRepository.save(report);
        return mapToResponse(saved);
    }

    @Override
    @Transactional(readOnly = true)
    public ReportResponse getReportById(String reportId) {
        String tenantId = TenantContext.getTenantId();
        AiReport report = reportRepository.findByIdAndTenantIdAndDeletedFalse(reportId, tenantId)
                .orElseThrow(() -> new ResourceNotFoundException("Report not found"));
        return mapToResponse(report);
    }

    @Override
    @Transactional(readOnly = true)
    public Page<ReportResponse> getReportsByEvent(String eventId, Pageable pageable) {
        String tenantId = TenantContext.getTenantId();
        return reportRepository.findByTenantIdAndEventIdAndDeletedFalse(tenantId, eventId, pageable).map(this::mapToResponse);
    }

    @Override
    @Transactional(readOnly = true)
    public byte[] exportReportPdf(String reportId) {
        String tenantId = TenantContext.getTenantId();
        AiReport report = reportRepository.findByIdAndTenantIdAndDeletedFalse(reportId, tenantId)
                .orElseThrow(() -> new ResourceNotFoundException("Report not found"));

        String pdfHeader = "%PDF-1.4 Mock Header\n" + report.getMarkdownContent();
        return pdfHeader.getBytes(StandardCharsets.UTF_8);
    }

    private ReportResponse mapToResponse(AiReport r) {
        return ReportResponse.builder()
                .id(r.getId())
                .eventId(r.getEvent().getId())
                .eventTitle(r.getEvent().getTitle())
                .reportType(r.getReportType())
                .title(r.getTitle())
                .markdownContent(r.getMarkdownContent())
                .status(r.getStatus())
                .generatedByEmail(r.getGeneratedBy() != null ? r.getGeneratedBy().getEmail() : "SYSTEM")
                .createdAt(r.getCreatedAt())
                .build();
    }
}
